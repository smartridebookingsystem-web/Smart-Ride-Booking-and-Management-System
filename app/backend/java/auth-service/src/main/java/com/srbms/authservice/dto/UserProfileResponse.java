package com.srbms.authservice.dto;

import java.time.LocalDate;

public class UserProfileResponse {
    private Integer userId;
    private String username;
    private String email;
    private String phone;
    private LocalDate dob;
    private String gender;
    private String role;
    private String status;
    private String profileImage;
    private String licenseNo; // null if not driver
    private String licensePdfUrl;

    public UserProfileResponse() {}

    public Integer getUserId() {
        return userId;
    }

    public void setUserId(Integer userId) {
        this.userId = userId;
    }

    public String getUsername() {
        return username;
    }

    public void setUsername(String username) {
        this.username = username;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPhone() {
        return phone;
    }

    public void setPhone(String phone) {
        this.phone = phone;
    }

    public LocalDate getDob() {
        return dob;
    }

    public void setDob(LocalDate dob) {
        this.dob = dob;
    }

    public String getGender() {
        return gender;
    }

    public void setGender(String gender) {
        this.gender = gender;
    }

    public String getRole() {
        return role;
    }

    public void setRole(String role) {
        this.role = role;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getProfileImage() {
        return profileImage;
    }

    public void setProfileImage(String profileImage) {
        this.profileImage = profileImage;
    }

    public String getLicenseNo() {
        return licenseNo;
    }

    public void setLicenseNo(String licenseNo) {
        this.licenseNo = licenseNo;
    }

    public String getLicensePdfUrl() {
        return licensePdfUrl;
    }

    public void setLicensePdfUrl(String licensePdfUrl) {
        this.licensePdfUrl = licensePdfUrl;
    }
}
